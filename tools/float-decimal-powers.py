#!/usr/bin/env python3
"""Generate the exact reciprocal power pairs used by binary64 formatting.

The representation follows Go's BSD-licensed unrounded scaling tables:
Go 1.27.3, commit 2aae1000ea1d4b28923b96db28acf4e3b99d6aff.
See third_party/go-float/LICENSE and docs/native-float-decimal.md.
All calculations here use exact integers; generation needs no Go toolchain.
"""
import argparse
import json
from pathlib import Path

MIN_POWER = -292
MAX_POWER = 324
WORD_BITS = 64
WORD_BASE = 1 << WORD_BITS
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'compiler/src/backend/qbe/runtime/float_powers.trb'


def power_pair(power):
    numerator = 10 ** max(power, 0)
    denominator = 10 ** max(-power, 0)
    # This fixed-point logarithm is exact throughout the registered table range.
    binary_exponent = (power * 108853) >> 15
    shift = 127 - binary_exponent
    if shift >= 0:
        numerator <<= shift
    else:
        denominator <<= -shift
    rounded_up = (numerator + denominator - 1) // denominator
    high = (rounded_up + WORD_BASE - 1) >> WORD_BITS
    low = (high << WORD_BITS) - rounded_up
    assert 0 <= high < WORD_BASE and 0 <= low < WORD_BASE
    return high, low


def signed_word(value):
    return value if value < WORD_BASE // 2 else value - WORD_BASE


def generated():
    words = [f'l {signed_word(value)}' for power in range(MIN_POWER, MAX_POWER + 1)
             for value in power_pair(power)]
    data = 'data $trbn_float_decimal_powers = align 8 { ' + ', '.join(words) + ' }\n'
    return ('import { QbeOutput, qbe_output_line } from backend/qbe/output\n\n'
            '# Generated by tools/float-decimal-powers.py; do not edit by hand.\n'
            '# 617 exact reciprocal pairs, decimal powers -292..324, hi*2^64-lo.\n'
            '# Go-derived representation; see third_party/go-float/LICENSE.\n'
            'def emit_float_decimal_powers(mut output: QbeOutput)\n'
            '\tqbe_output_line(output, ' + json.dumps(data) + ')\nend\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    wanted = generated()
    if args.write:
        OUTPUT.write_text(wanted)
    elif not OUTPUT.exists() or OUTPUT.read_text() != wanted:
        raise SystemExit('Float decimal powers are stale; run tools/float-decimal-powers.py --write')
    print('PASS exact Float decimal power table')
