import { readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'docs/capabilities/benchmarks/data.js');
const runtimeRoot = 'results/2026-09-02-benchmarksgame-runtime-lexical-loop-index-linux-arm64';
const buildRoot = 'results/2026-09-02-benchmarksgame-build-lexical-loop-index-linux-arm64';
const cases = ['fannkuch-redux', 'n-body', 'spectral-norm'];
const lanes = ['one-core', 'four-core'];
const labels = {
  'typerb-native': 'TypeRB Native',
  'typerb-go': 'TypeRB Go',
  c: 'C',
  cpp: 'C++',
  go: 'Go',
  rust: 'Rust',
  java: 'Java',
};

const publicFileUrl = (path) => `https://github.com/type-rb/type-rb-native/blob/main/${path}`;

const parseTsv = async (path) => {
  const text = await readFile(resolve(root, path), 'utf8');
  const [header, ...lines] = text.trim().split('\n').map((line) => line.split('\t'));
  return lines.map((values) => Object.fromEntries(header.map((name, index) => [name, values[index]])));
};

const number = (value, field, path) => {
  const parsed = Number(value);
  if (!Number.isFinite(parsed)) throw new Error(`${path}: ${field} is not numeric`);
  return parsed;
};

const runtime = [];
for (const caseName of cases) {
  for (const lane of lanes) {
    const path = `${runtimeRoot}/benchmarksgame-runtime-${caseName}/${lane}-evidence/medians.tsv`;
    const rows = await parseTsv(path);
    for (const row of rows) {
      runtime.push({
        case: row.case,
        lane: row.lane,
        candidate: row.candidate,
        label: labels[row.candidate] ?? row.candidate,
        retained: number(row.retained, 'retained', path),
        passed: number(row.passed, 'passed', path),
        wallSeconds: number(row.walltime_median_seconds, 'walltime_median_seconds', path),
        cpuSeconds: number(row.cputime_median_seconds, 'cputime_median_seconds', path),
        memoryBytes: number(row.memory_median_bytes, 'memory_median_bytes', path),
        status: row.status,
        evidence: publicFileUrl(path),
      });
    }
  }
}

const build = [];
for (const caseName of cases) {
  const path = `${buildRoot}/benchmarksgame-build-${caseName}/build-evidence/medians.tsv`;
  const rows = await parseTsv(path);
  for (const row of rows) {
    build.push({
      case: row.case,
      candidate: row.candidate,
      label: labels[row.candidate] ?? row.candidate,
      retained: number(row.retained, 'retained', path),
      passed: number(row.passed, 'passed', path),
      wallSeconds: number(row.walltime_median_seconds, 'walltime_median_seconds', path),
      cpuSeconds: number(row.cputime_median_seconds, 'cputime_median_seconds', path),
      memoryBytes: number(row.memory_median_bytes, 'memory_median_bytes', path),
      artifactBytes: number(row.artifact_bytes_median, 'artifact_bytes_median', path),
      artifactReproducible: row.artifact_reproducible === 'true',
      status: row.status,
      evidence: publicFileUrl(path),
    });
  }
}

const dataset = {
  schemaVersion: 1,
  snapshot: '2026-09-02 · Native aad4954',
  platform: 'Linux arm64 · Ubuntu 24.04 · 4 × Neoverse N2',
  runtime: {
    retained: runtime.reduce((total, row) => total + row.retained, 0),
    warmups: 84,
    records: runtime,
    result: publicFileUrl(`${runtimeRoot}/README.md`),
  },
  build: {
    retained: build.reduce((total, row) => total + row.retained, 0),
    records: build,
    result: publicFileUrl(`${buildRoot}/README.md`),
  },
  methodology: publicFileUrl('docs/benchmarksgame.md'),
};

const output = `// Generated by tools/benchmark-pages-data.mjs. Do not edit directly.\nexport const benchmarkData = Object.freeze(${JSON.stringify(dataset, null, 2)});\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    console.error(`${relative(root, outputPath)} is stale; run node tools/benchmark-pages-data.mjs`);
    process.exitCode = 1;
  } else {
    console.log(`PASS benchmark Pages data (${runtime.length} runtime rows, ${build.length} build rows)`);
  }
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Wrote ${relative(root, outputPath)}`);
}
