#!/usr/bin/env python3
"""Generate Unicode print ranges for the pinned reference's assertion quoting."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
EXPORTER = r'''package main
import ("crypto/sha256"; "encoding/hex"; "encoding/json"; "os"; "strconv"; "unicode")
func main() {
 ranges := [][2]int{}
 start := -1
 digest := sha256.New()
 for point := 0; point <= unicode.MaxRune; point++ {
  printable := strconv.IsPrint(rune(point))
  if printable != unicode.IsPrint(rune(point)) { panic("Unicode print classification differs") }
  if printable { digest.Write([]byte{1}) } else { digest.Write([]byte{0}) }
  if printable && start < 0 { start = point }
  if !printable && start >= 0 { ranges = append(ranges, [2]int{start, point-1}); start = -1 }
 }
 if start >= 0 { ranges = append(ranges, [2]int{start, unicode.MaxRune}) }
 json.NewEncoder(os.Stdout).Encode(struct { Version string; Ranges [][2]int; Digest string }{
  unicode.Version, ranges, hex.EncodeToString(digest.Sum(nil))})
}'''


def render(data):
    if data["Version"] != "17.0.0":
        raise ValueError("Unicode changes require an explicit reference review")
    values = bytearray(0x110000)
    previous = -2
    for first, last in data["Ranges"]:
        if not previous + 1 < first <= last < len(values):
            raise ValueError("noncanonical print ranges")
        values[first:last + 1] = bytes([1]) * (last - first + 1)
        previous = last
    if hashlib.sha256(values).hexdigest() != data["Digest"]:
        raise ValueError("ranges differ from exhaustive reference classification")
    ranges = ", ".join(str(value) for pair in data["Ranges"] for value in pair)
    source = "def test_print_ranges(): Array<Integer>\nreturn [" + ranges + "]\nend\n"
    return ("# Generated by tools/test-inspection-data.py; do not edit by hand.\n"
            "# Unicode 17.0.0 print classification, checked against every Go rune.\n"
            "# Classification SHA-256: " + data["Digest"] + "\n"
            "def native_test_print_ranges_source(): String\n\treturn "
            + json.dumps(source) + "\nend\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--go", default="go")
    parser.add_argument("--evidence", type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="test-inspection-unicode-") as directory:
        source = Path(directory) / "main.go"
        source.write_text(EXPORTER)
        result = subprocess.run([args.go, "run", str(source)], check=True, capture_output=True,
                                text=True, env=dict(os.environ, GOWORK="off"), timeout=60)
    data = json.loads(result.stdout)
    generated = render(data)
    path = ROOT / "compiler/src/project/test_inspection_data.trb"
    if args.check:
        if path.read_text() != generated:
            raise ValueError("assertion print ranges differ from the reference Unicode data")
    else:
        path.write_text(generated)
    if args.evidence:
        args.evidence.write_text(json.dumps(data) + "\n")
    print(f"PASS Unicode {data['Version']} assertion classification: all 1,114,112 code points")


if __name__ == "__main__":
    main()
