#!/usr/bin/env python3
"""Regenerate JSON diagnostic character properties from the reference Go toolchain."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
BEGIN = '# BEGIN GENERATED JSON DIAGNOSTIC DATA'
END = '# END GENERATED JSON DIAGNOSTIC DATA'
EXPORTER = r'''package main
import ("crypto/sha256"; "encoding/hex"; "encoding/json"; "os"; "strconv"; "unicode")
func main() {
 predicates := []func(rune) bool{strconv.IsPrint, unicode.IsSpace}
 tables := make([][][2]int, len(predicates))
 flags := make([]byte, unicode.MaxRune+1)
 for bit, predicate := range predicates {
  start := -1
  for point := 0; point <= unicode.MaxRune+1; point++ {
   yes := point <= unicode.MaxRune && predicate(rune(point))
   if yes { flags[point] |= 1 << bit; if start < 0 { start = point } }
   if !yes && start >= 0 { tables[bit] = append(tables[bit], [2]int{start, point-1}); start = -1 }
  }
 }
 sum := sha256.Sum256(flags)
 json.NewEncoder(os.Stdout).Encode(struct {Version string; Tables [][][2]int; Digest string}{unicode.Version, tables, hex.EncodeToString(sum[:])})
}'''


def render(data):
    lines = [BEGIN, '# Generated by tools/json-diagnostic-data.py; do not edit by hand.',
             f"# Go Unicode {data['Version']}: printable runes and whitespace.",
             '# Ordered ranges encode six hexadecimal digits for each bound.', '']
    flags = bytearray(0x110000)
    for bit, name in enumerate(('printable', 'space')):
        previous = -1
        encoded = ''
        for low, high in data['Tables'][bit]:
            if not previous < low <= high <= 0x10ffff:
                raise ValueError('invalid ordered Unicode range')
            previous = high
            encoded += f'{low:06x}{high:06x}'
            for point in range(low, high + 1):
                flags[point] |= 1 << bit
        lines += [f'def _diagnostic_{name}_data(): String', f'\treturn "{encoded}"', 'end', '']
    if hashlib.sha256(flags).hexdigest() != data['Digest']:
        raise ValueError('ranges differ from Go diagnostic predicates')
    return '\n'.join(lines) + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--go', default='go')
    parser.add_argument('--evidence', type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='json-diagnostic-unicode-') as temporary:
        source = Path(temporary) / 'main.go'
        source.write_text(EXPORTER)
        result = subprocess.run([args.go, 'run', source], check=True, capture_output=True,
                                text=True, env=dict(os.environ, GOWORK='off'), timeout=60)
    data = json.loads(result.stdout)
    generated = render(data)
    target = ROOT / 'compiler/packages/internal/json.trb'
    current = target.read_text()
    if BEGIN in current:
        before, tail = current.split(BEGIN, 1)
        _, after = tail.split(END, 1)
        updated = before + generated + after
    else:
        updated = current.rstrip() + '\n\n' + generated + '\n'
    if args.check:
        if updated != current:
            raise ValueError('JSON diagnostic data differs from the reference Go toolchain')
    else:
        target.write_text(updated)
    if args.evidence:
        args.evidence.write_text(json.dumps(data, indent=2) + '\n')
    print(f"Unicode {data['Version']}: all 1,114,112 diagnostic classifications agree with Go")


if __name__ == '__main__':
    main()
